import { readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const root = fileURLToPath(new URL('../', import.meta.url));
assert.ok(process.argv[2], 'Usage: node scripts/sync-manga-effects.mjs /path/to/manga-authors');
const sourceRoot = resolve(process.argv[2]), target = join(root, 'data/effect-sources');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const raw = await readFile(join(sourceRoot, 'authors.json'), 'utf8');
const authors = JSON.parse(raw);
const adaptations = JSON.parse(await readFile(join(target, 'manga-adaptations.json'), 'utf8'));
const labels = JSON.parse(await readFile(join(target, 'manga-labels.json'), 'utf8'));
assert.equal(authors.length, 100);
assert.equal(authors.filter(author => author.creator_type === 'manga-artist').length, 80);
assert.equal(authors.filter(author => author.creator_type === 'illustrator').length, 20);
assert.equal(new Set(authors.map(author => author.id)).size, 100);
assert.deepEqual(Object.keys(adaptations).sort(), authors.map(author => author.id).sort());
assert.deepEqual(Object.keys(labels).sort(), authors.map(author => author.id).sort());

const effects = [], snapshots = [];
for (const author of authors) {
  assert.match(author.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
  assert.ok(author.name_zh && author.name && author.recent_focus?.work && adaptations[author.id]);
  const id = `manga-${author.id}`, path = `manga-authors/authors/${author.id}`;
  const files = [];
  for (const name of ['SKILL.md', 'drawing.md', 'prompts.md', 'manifest.json']) {
    const content = await readFile(join(sourceRoot, 'authors', author.id, name), 'utf8');
    files.push({ name, content, sha256: sha256(content) });
  }
  const snapshot = `# ${author.name_zh} · 本地研究卡快照\n\n来源：human-distillation-lab 工作目录（不假定已提交）。\n仅供查阅；出图采用项目内独立转写的线条和明暗方法。\n\n` + files.map(file => `## ${path}/${file.name}\n\n${file.content}`).join('\n\n');
  const digest = sha256(snapshot);
  const source = { name: author.name_zh, path: `${path}/SKILL.md`, revision: `local-sha256:${digest}`, url: `/api/effect-sources/${id}` };
  const description = adaptations[author.id];
  assert.ok(labels[author.id].work && labels[author.id].genre);
  const styleTarget = `${author.name_zh}《${labels[author.id].work}》${labels[author.id].credit ? `（${labels[author.id].credit}）` : ''}`;
  const effect = {
    id, label: author.name_zh, group: author.family, creatorType: author.creator_type,
    focus: author.recent_focus, description,
    promptLabel: styleTarget,
    prompt: `明确画风目标：${styleTarget}的绘画风格，作者原名：${author.name}。作者与作品是本次风格要求，不是仅供展示的标签；将该画风的造型语言、线条、明暗、材质概括和色块组织一致地用于整张图。具体视觉技法：${description} 黑白或彩色服从所选视觉类型，彩色时保留参考配色并用所选画风重新表现明暗。参考图约束主体身份、物种结构、骨架姿态、发型与衣装或体表设计；五官关系和设计特征用目标画风重新造型。脸部轮廓的概括、眼鼻嘴的画法和明暗几何优先遵循目标作者；用发型、五官关系和衣装保持身份可辨识，不要求照片式的写实相似度。不保留参考照片的皮肤、衣料纹理和摄影光影。主体须从形体到材质完整重绘，不能只在写实人物外加速度线或漫画贴纸。沿用用户主体和故事，不替换成作品中的既有角色、服装或标志，不添加作者签名；资料图分区要求优先。`,
    medium: author.creator_type === 'illustrator' ? 'illustration' : 'manga',
    mediums: ['manga', 'comic', ...(author.creator_type === 'illustrator' ? ['illustration'] : [])],
    source
  };
  // A source or adaptation change must not reuse images generated with the previous recipe.
  effect.revision = sha256(JSON.stringify(effect));
  // Genre remains display-only; author/work/credit above are explicit style inputs.
  effect.display = labels[author.id];
  effects.push(effect);
  snapshots.push({ id, file: `data/effect-sources/${id}.md`, sha256: digest, source, files: files.map(({ name, sha256 }) => ({ path: `${path}/${name}`, sha256 })), content: snapshot });
}
const manifest = JSON.parse(await readFile(join(target, 'manifest.json'), 'utf8'));
manifest.effects = [...manifest.effects.filter(effect => !effect.id.startsWith('manga-')), ...snapshots.map(({ content, ...entry }) => entry)];
manifest.mangaAuthors = { count: 100, mangaArtists: 80, illustrators: 20, file: 'data/effect-sources/manga-authors.json', sha256: sha256(raw), source: 'human-distillation-lab/manga-authors/authors.json (local working copy)', imageValidation: 'not-run' };
for (const snapshot of snapshots) await writeFile(join(root, snapshot.file), snapshot.content);
await writeFile(join(target, 'manga-authors.json'), raw);
await writeFile(join(root, 'public/manga-effects.js'), `// Generated by scripts/sync-manga-effects.mjs; edit manga-adaptations.json, then sync.\nexport const MANGA_EFFECTS = ${JSON.stringify(effects, null, 2)};\n`);
await writeFile(join(target, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log('Synced 100 local schemes: 80 manga artists + 20 illustrators. No image generation performed.');
